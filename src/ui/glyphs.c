const char *const *glyph_rows(GlyphId id, int size)
{
    if ((unsigned)id >= (unsigned)GLYPH_COUNT)
        return NULL;
    if (size == 16)
        return glyphs16[id];
    if (size == 8)
        return glyphs8[id];
    return NULL;
}

int glyph_pack(const char *const *rows, int size, unsigned short *out)
{
    int y, x;

    for (y = 0; y < size; y++) {
        unsigned short word = 0;

        if (strlen(rows[y]) != (size_t)size)
            return -1;
        for (x = 0; x < size; x++) {
            if (rows[y][x] == '#')
                word |= (unsigned short)(0x8000u >> x);
            else if (rows[y][x] != '.')
                return -1;
        }
        out[y] = word;
    }
    return 0;
}
